#!/usr/bin/env python
"""Generate ``docs/variables.md`` from the packaged metadata.

Reads ``src/climateeval/variables.yml`` and ``src/climateeval/coordinates.yml``
and writes a Markdown reference of the known variables and coordinates. Run it
whenever those YAML files change::

    python scripts/gen_variables_doc.py

Uses only the standard library plus PyYAML (a ClimateEval dependency).
"""

from __future__ import annotations

from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
PKG = REPO_ROOT / "src" / "climateeval"
VARIABLES_YML = PKG / "variables.yml"
COORDINATES_YML = PKG / "coordinates.yml"
OUTPUT = REPO_ROOT / "docs" / "variables.md"

HEADER = """\
<!-- This file is generated by scripts/gen_variables_doc.py -->
<!-- Do not edit by hand; edit variables.yml / coordinates.yml and regenerate. -->

# Variables and coordinates

Reference of the variables and coordinates ClimateEval knows about. The metadata
below is loaded from `src/climateeval/variables.yml` and
`src/climateeval/coordinates.yml`; a suite may use any subset of these, and a
`var_name` in a suite YAML must appear in the variables table.

Regenerate this page after editing either YAML file:

```bash
python scripts/gen_variables_doc.py
```
"""


def _md_cell(value: object) -> str:
    """Render one table cell, wrapping non-empty scalars in backticks."""
    text = "" if value is None else str(value)
    return f"`{text}`" if text else ""


def _variables_table(variables: dict) -> str:
    """Render the variables table, sorted by variable name."""
    lines = [
        "## Variables",
        "",
        "| Variable | Long name | Standard name | Units | Realm | Coordinates | Derived |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in sorted(variables):
        meta = variables[name] or {}
        coords = " ".join(meta.get("coordinates", []) or [])
        derived = "yes" if meta.get("derived", False) else ""
        lines.append(
            f"| `{name}` "
            f"| {meta.get('long_name', '') or ''} "
            f"| {_md_cell(meta.get('standard_name'))} "
            f"| {_md_cell(meta.get('units'))} "
            f"| {_md_cell(meta.get('realm'))} "
            f"| {_md_cell(coords)} "
            f"| {derived} |",
        )
    return "\n".join(lines)


def _coordinates_tables(coordinates: dict) -> str:
    """Render specific and generic coordinate tables."""
    specific = {
        name: meta
        for name, meta in coordinates.items()
        if not (meta or {}).get("allowed_coordinates")
    }
    generic = {
        name: meta
        for name, meta in coordinates.items()
        if (meta or {}).get("allowed_coordinates")
    }

    lines = [
        "## Coordinates",
        "",
        "| Coordinate | Long name | Standard name | Units |",
        "| --- | --- | --- | --- |",
    ]
    for name in sorted(specific):
        meta = specific[name] or {}
        lines.append(
            f"| `{name}` "
            f"| {meta.get('long_name', '') or ''} "
            f"| {_md_cell(meta.get('standard_name'))} "
            f"| {_md_cell(meta.get('units'))} |",
        )

    if generic:
        lines += [
            "",
            "### Generic coordinates",
            "",
            "A generic coordinate matches any one of its allowed coordinates.",
            "",
            "| Coordinate | Allowed coordinates |",
            "| --- | --- |",
        ]
        for name in sorted(generic):
            allowed = (generic[name] or {}).get("allowed_coordinates", [])
            allowed_md = ", ".join(f"`{c}`" for c in allowed)
            lines.append(f"| `{name}` | {allowed_md} |")
    return "\n".join(lines)


def main() -> None:
    """Read the YAML metadata and write ``docs/variables.md``."""
    variables = yaml.safe_load(VARIABLES_YML.read_text())
    coordinates = yaml.safe_load(COORDINATES_YML.read_text())

    content = "\n".join(
        [
            HEADER,
            _variables_table(variables),
            "",
            _coordinates_tables(coordinates),
            "",
        ],
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} "  # noqa: T201
          f"({len(variables)} variables, {len(coordinates)} coordinates)")


if __name__ == "__main__":
    main()
