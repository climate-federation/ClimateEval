class ChlBGCEvaluation(SimpleDiagnostic):
    """
    Full Chl-a BGC evaluation diagnostic.

    Per model:
      1. _get_cube()    — select the 4D surface chl cube from multi-cube input
      2. _preprocess()  — regrid to 2x2, compute time mean → metrics table
      3. get_output()   — run all 12 figure phases, then call super() for metrics

    Multi-model figures (fig1+2, fig3, fig4) accumulate model_clim/model_seasonal
    across all get_output() calls and are written on the last model.
    """

    _final_coordinates = (Coordinate("lat"), Coordinate("lon"))

    # Shared state across models — populated in get_output()
    _obs_full: Any = None
    _obs_clim: Any = None
    _model_clim: dict = {}
    _model_seasonal: dict = {}
    _model_chl_ts: dict = {}
    _common_grid: Any = None
    _obs_mld_ts: Any = None
    _obs_sst_ts: Any = None
    _model_mld_ts: dict = {}
    _model_sst_ts: dict = {}
    _model_siconc_ts: dict = {}
    _obs_rsds_ts: Any = None
    _model_rsds_ts: dict = {}
    _models_processed: list = []

    # The suite constructs a fresh instance per model (seven times for
    # this recipe), so anything logged in __init__ repeats. These keep
    # the two startup banners to one appearance each.
    _banner_shown: bool = False
    _masking_logged: bool = False

    # Keyword arguments this diagnostic owns. The suite passes them
    # through `diagnostic_kwargs`, which it forwards verbatim to the
    # constructor, so anything the base class does not declare has to be
    # taken out here or __init__ raises TypeError and every model fails
    # before a single figure is drawn. Reading them off `self` later is
    # not enough -- that was the bug: `_requested_figures` and
    # `_resolve_out_dir` both read attributes that nothing had set.
    _OWN_KWARGS = (
        "figures",            # recipe keys to produce; see _requested_figures
        "figure_options",     # per-figure options dict from the recipe
        "output_dir",         # where figures are written; see _resolve_out_dir
        "mask_to_obs",        # blank models where the reference has no retrieval
        "mask_reference",
        "mask_min_retained",
        "mask_warn_below",
    )

    def __init__(self, *args, **kwargs):
        for name in self._OWN_KWARGS:
            setattr(self, name, kwargs.pop(name, None))
        super().__init__(*args, **kwargs)

        # Per-instance copies of the accumulators. They are declared as
        # class attributes above so the multi-model figures can collect
        # across models, which only works because the suite reuses one
        # instance; if it ever constructs one per model the figures would
        # silently lose every model but the last, so assert the shape we
        # rely on rather than discover it from an empty figure.
        if self.figures and not ChlBGCEvaluation._banner_shown:
            ChlBGCEvaluation._banner_shown = True
            want = {str(x) for x in self.figures}
            logger.info(
                f"ChlBGCEvaluation: recipe requests {len(want)} figure(s); "
                f"{len(want & set(FIGURE_KEYS))} implemented here, "
                f"{len(want - set(FIGURE_KEYS))} not")
        # Masking is implemented in the script, not here: it is switched
        # by CHL_MASK_TO_OBS, which the script reads at import. By the
        # time this constructor runs the script is already imported, so
        # all that can be done here is check the two agree -- a mismatch
        # means figures drawn from unmasked fields under a _maskedobs/
        # directory name, which is worse than either option on its own.
        script_masking = bool(getattr(_S, "MASK_TO_OBS", False))
        if bool(self.mask_to_obs) != script_masking:
            logger.warning(
                f"ChlBGCEvaluation: recipe says mask_to_obs="
                f"{bool(self.mask_to_obs)} but {_SCRIPT.name} was imported "
                f"with MASK_TO_OBS={script_masking}. The figures will NOT "
                f"match the directory name. CHL_MASK_TO_OBS has to be set "
                f"before the script is imported -- the driver does this "
                f"right after reading the recipe.")
        elif not ChlBGCEvaluation._masking_logged:
            ChlBGCEvaluation._masking_logged = True
            logger.info(
                f"ChlBGCEvaluation: masking to the observational sampling "
                f"is {'ON' if script_masking else 'OFF'}")

    # ------------------------------------------------------------------ #
    # Cube selection and preprocessing                                     #
    # ------------------------------------------------------------------ #

    def _get_cube(self, data, variable):
        """Select the full 4D chl cube from multi-cube CubeList."""
        import iris
        chl_cubes = data.extract(iris.Constraint(
            cube_func=lambda c: (
                c.var_name == "chl" or
                "chlorophyll" in c.name().lower()
            )
        ))
        four_d = [c for c in chl_cubes if c.ndim == 4]
        if four_d:
            cube = four_d[0]
        elif chl_cubes:
            cube = chl_cubes[0]
        else:
            raise ValueError(
                f"No chl cube found. Available: {[c.name() for c in data]}"
            )
        return self._safely_preprocess(cube, variable)

    def _preprocess(self, cube: Cube, variable=None) -> Cube:
        """Select surface level, regrid to 2x2, compute time mean."""
        if cube.ndim == 4:
            cube = cube[..., 0, :, :]
        with setup_esmvaltool_config_and_logging():
            cube = regrid(cube, DEFAULT_GRID, "linear", cache_weights=True)
            cube = climate_statistics(cube, "mean", "full")
        return cube

    # ------------------------------------------------------------------ #
    # get_output — run figures then metrics                                #
    # ------------------------------------------------------------------ #

    def get_output(self, data: Any, data_information: Any) -> Any:
        """Run figure phases for this model, then delegate to parent."""
        model = data_information.name
        logger.info(f"ChlBGCEvaluation: processing {model}")

        try:
            self._accumulate_model_data(model)
        except Exception as exc:
            import traceback
            logger.warning(f"  [{model}] data accumulation failed: {exc}")
            logger.opt(colors=False).warning(traceback.format_exc())

        # Call parent for metrics table
        result = super().get_output(data, data_information)

        # After last model — generate multi-model figures
        self._models_processed.append(model)
        if len(self._models_processed) >= len(_S.MODELS):
            try:
                self._run_multi_model_figures()
            except Exception as exc:
                import traceback
                logger.warning(f"  Multi-model figures failed: {exc}")
                logger.opt(colors=False).warning(traceback.format_exc())

        return result

    # ------------------------------------------------------------------ #
    # Data accumulation — called once per model                           #
    # ------------------------------------------------------------------ #

    def _accumulate_model_data(self, model: str) -> None:
        """Load all variables for one model and store in class state."""
        s = _S

        # Load obs once
        if self._obs_full is None:
            self._obs_full = s.load_obs_chl()
            self._obs_clim = self._obs_full.mean("time", keep_attrs=True)

        # Chl
        try:
            da = s.load_model_chl(model)
            self._model_chl_ts[model] = da
            clim_native = da.mean("time", keep_attrs=True)
            self._model_clim[model] = s.regrid_to_obs(clim_native,
                                                       self._obs_clim)
            try:
                months = da.groupby("time.month").mean("time")
                regridded = []
                for m in months.month.values:
                    re = s.regrid_to_obs(months.sel(month=m), self._obs_clim)
                    regridded.append(re.expand_dims(month=[m]))
                self._model_seasonal[model] = xr.concat(regridded, dim="month")
            except Exception as e:
                logger.warning(f"  [{model}] seasonal regrid failed: {e}")
        except FileNotFoundError as e:
            logger.warning(f"  [{model}] chl not found: {e}")
            return

        # The common grid does not depend on ORAS5.
        #
        # It used to be built from load_obs_mld(), which streams ORAS5
        # over OPeNDAP from apdrc.soest.hawaii.edu. Compute nodes have no
        # outbound network, so that call fails for every model, leaving
        # _common_grid as None - and Phase B is wrapped in
        # `if common_grid is not None`, so ONE unreachable URL suppressed
        # the SST and cloud bias maps too, neither of which needs ORAS5.
        #
        # A plain 1 degree grid is what ORAS5's 1x1 distribution provided
        # anyway, so building it directly costs nothing and keeps the
        # rest of Phase B alive when the reanalysis cannot be reached.
        if self._common_grid is None:
            self._common_grid = xr.DataArray(
                np.zeros((180, 360)),
                dims=("lat", "lon"),
                coords={"lat": np.arange(-89.5, 90.0, 1.0),
                        "lon": np.arange(0.5, 360.0, 1.0)},
            )
            logger.info("  common grid: 1 deg global (independent of ORAS5)")

        # ORAS5 itself, separately: its absence must not take the grid,
        # or Phase B, down with it.
        try:
            if self._obs_mld_ts is None:
                self._obs_mld_ts = s.load_obs_mld()
        except Exception as e:
            logger.warning(f"  ORAS5 MLD reference unavailable: {e}")
            logger.warning("  -> Fig 5 (MLD bias) will be skipped; "
                           "Figs 6-7 are unaffected")

        try:
            mld_native = s.load_model_mld(model)
            if mld_native is not None:
                mld_re = s.regrid_timeseries(mld_native, self._common_grid)
                self._model_mld_ts[model] = mld_re
        except Exception as e:
            logger.warning(f"  [{model}] model MLD failed: {e}")

        # SST
        try:
            if self._obs_sst_ts is None:
                self._obs_sst_ts = s.load_obs_sst()
            sst_native = s.load_model_sst(model)
            if sst_native is not None:
                self._model_sst_ts[model] = sst_native
        except Exception as e:
            logger.warning(f"  [{model}] SST failed: {e}")

        # siconc
        try:
            sic = s.load_model_siconc(model)
            if sic is not None:
                self._model_siconc_ts[model] = sic
        except Exception as e:
            logger.warning(f"  [{model}] siconc failed: {e}")

        # rsds, for the polar light-coupling figure. Not loaded before,
        # which is why that figure could not be produced here.
        try:
            if self._obs_rsds_ts is None:
                self._obs_rsds_ts = s.load_obs_rsds()
            rsds = s.load_model_rsds(model)
            if rsds is not None:
                self._model_rsds_ts[model] = rsds
        except Exception as e:
            logger.warning(f"  [{model}] rsds failed: {e}")

        logger.success(f"  [{model}] data accumulated")

    # ------------------------------------------------------------------ #
    # Multi-model figures — called once after all models processed        #
    # ------------------------------------------------------------------ #

    # ------------------------------------------------------------------ #
    # Configuration supplied by the suite                                  #
    # ------------------------------------------------------------------ #

    def _requested_figures(self) -> set:
        """Figure keys the suite asked for.

        Read defensively: the suite passes `figures` through
        diagnostic_kwargs, but how the base class stores them is not
        part of any contract this file can rely on. CHL_FIGURES
        overrides for a one-off run; with neither, the full set this
        diagnostic implements is produced.
        """
        for attr in ("figures", "_figures"):
            v = getattr(self, attr, None)
            if v:
                return {str(x) for x in v}
        env = os.environ.get("CHL_FIGURES", "").strip()
        if env:
            return {tok.strip() for tok in env.split(",") if tok.strip()}
        return set(FIGURE_KEYS)

    def _obs_siconc_ts(self):
        """Observed sea ice, loaded once and reused.

        Figures 8 and 9 both need it and the loader is not cheap; a
        failure is reported once rather than per figure.
        """
        if getattr(self, "_obs_siconc_cache", _UNSET) is _UNSET:
            try:
                self._obs_siconc_cache = _S.load_obs_siconc()
            except Exception as exc:
                logger.warning(f"  observed sea ice unavailable: {exc}")
                self._obs_siconc_cache = None
        return self._obs_siconc_cache

    def _resolve_out_dir(self) -> Path:
        """Output directory, and point the script at it too.

        The script writes through its own module-level OUT_DIR, so
        setting it here is what actually redirects the figures; changing
        only this module's constant would move the log message and
        nothing else.
        """
        d = Path(getattr(self, "output_dir", None) or OUT_DIR)
        d.mkdir(parents=True, exist_ok=True)
        try:
            _S.OUT_DIR = d
        except Exception as exc:
            logger.warning(f"  could not redirect script output: {exc}")
        if _NEWFIGS is not None:
            try:
                _NEWFIGS.OUT_DIR = d
            except Exception:
                pass
        return d

    # ------------------------------------------------------------------ #
    # Multi-model figures — called once after all models processed        #
    # ------------------------------------------------------------------ #

    def _run_multi_model_figures(self) -> None:
        """Generate the requested manuscript figures."""
        s = _S
        obs_full = self._obs_full
        obs_clim = self._obs_clim
        model_seasonal = self._model_seasonal
        model_chl_ts = self._model_chl_ts
        common_grid = self._common_grid
        obs_mld_ts = self._obs_mld_ts
        obs_sst_ts = self._obs_sst_ts
        model_mld_ts = self._model_mld_ts
        model_sst_ts = self._model_sst_ts
        model_siconc_ts = self._model_siconc_ts

        want = self._requested_figures()
        out_dir = self._resolve_out_dir()
        runnable = sorted(want & set(FIGURE_KEYS))
        skipped = sorted(want - set(FIGURE_KEYS))

        logger.info(f"=== Figures requested: {len(want)}; "
                    f"this diagnostic produces {len(runnable)} ===")
        for k in runnable:
            logger.info(f"    {FIGURE_KEYS[k]}")
        if skipped:
            logger.warning(
                f"  not implemented here, still in the standalone "
                f"scripts: {', '.join(skipped)}")
        logger.info(f"  output -> {out_dir}")

        def run(key, fn, label):
            """Run one figure if asked for, and never let it stop the rest."""
            if key not in want:
                return
            try:
                fn()
            except Exception as exc:
                import traceback
                logger.warning(f"  {label} failed: {exc}")
                logger.opt(colors=False).warning(traceback.format_exc())

        # ── Fig. 1: observed mean state and Taylor diagram ───────────
        if _NEWFIGS is not None and model_chl_ts and common_grid is not None:
            run("fig01_meanstate_taylor",
                lambda: _NEWFIGS.make_fig1_obs_and_taylor(
                    obs_full, model_chl_ts, common_grid),
                "Fig. 1")
        elif "fig01_meanstate_taylor" in want:
            logger.warning("  Fig. 1 skipped: chl_newfigs unavailable or "
                           "no model Chl-a accumulated")

        # ── Fig. 2: seasonal cycle ───────────────────────────────────
        if model_seasonal:
            run("fig02_seasonal_cycle",
                lambda: s.make_fig4(obs_full, model_seasonal), "Fig. 2")

        # ── Fig. 3: interannual sigma ratio ──────────────────────────
        if _NEWFIGS is not None and model_chl_ts and common_grid is not None:
            run("fig03_sigma_ratio",
                lambda: _NEWFIGS.make_fig_sigma_ratio_seasonal(
                    obs_full, model_chl_ts, common_grid),
                "Fig. 3")

        # ── Figs. 4 and 5: seasonal phasing and covariability ────────
        if _SP is not None and model_chl_ts and (
                {"fig04_seasonal_covariability", "fig05_phase_lags"} & want):
            obs_siconc_ts = self._obs_siconc_ts()
            obs_fields = {"chl": obs_full, "mlotst": obs_mld_ts,
                          "tos": obs_sst_ts, "siconc": obs_siconc_ts}
            model_fields = {
                m: {"chl": model_chl_ts.get(m),
                    "mlotst": model_mld_ts.get(m),
                    "tos": model_sst_ts.get(m),
                    "siconc": model_siconc_ts.get(m)}
                for m in model_chl_ts
            }
            run("fig04_seasonal_covariability",
                lambda: _SP.make_seasonal_phase_figures(
                    obs_fields, model_fields, out_dir,
                    # The script's loaders already return Chl-a in
                    # mg m-3, so the units attribute must not be applied
                    # a second time. Sea ice is left to the automatic
                    # percent/fraction detection, which handles either.
                    scales={"chl": 1.0}),
                "Figs. 4-5")
            # Both figures come from the one call; mark the second done
            # so it is not attempted again.
            want = want - {"fig05_phase_lags"}

        # ── Driver bias maps: Figs. S10 and S13 ──────────────────────
        if common_grid is not None:
            obs_mld_clim = obs_mld_ts.mean("time", keep_attrs=True) \
                if obs_mld_ts is not None else None

            if "figS13_mld_bias" in want and obs_mld_clim is not None:
                mld_bias = {}
                for model, mld_re in model_mld_ts.items():
                    mld_bias[model] = mld_re.mean("time") - obs_mld_clim
                if mld_bias:
                    run("figS13_mld_bias",
                        lambda: s.make_bias_map_2x2(
                            mld_bias, obs_mld_clim,
                            vmin=-50, vmax=50, unit_label="m", cmap="RdBu_r",
                            fig_num=5, title="MLD bias: model - ORAS5",
                            filename="fig5_mld_bias.png",
                            stat_fmt="mean={mean:.1f} m  RMSE={rmse:.1f} m",
                        ), "Fig. S13")

            if "figS10_sst_bias" in want and obs_sst_ts is not None:
                obs_sst_clim = obs_sst_ts.mean("time", keep_attrs=True)
                sst_bias = {}
                for model, sst_native in model_sst_ts.items():
                    try:
                        sst_clim = sst_native.mean("time", keep_attrs=True)
                        sst_bias[model] = (
                            s.regrid_to_obs(sst_clim, obs_sst_clim)
                            - obs_sst_clim)
                    except Exception as exc:
                        logger.warning(f"  [{model}] SST bias failed: {exc}")
                if sst_bias:
                    # The reference name must match Section 2 of the
                    # manuscript; the two disagreed while the script used
                    # ERSSTv5 and the text still said ERSSTv3b.
                    ref = getattr(s, "SST_OBS_NAME", "NOAA-ERSSTv5")
                    run("figS10_sst_bias",
                        lambda: s.make_bias_map_2x2(
                            sst_bias, obs_sst_clim,
                            vmin=-3, vmax=3, unit_label="\u00b0C",
                            cmap="RdBu_r", fig_num=6,
                            title=f"SST bias: model - {ref}",
                            filename="fig6_sst_bias.png",
                            stat_fmt=("mean={mean:.2f} \u00b0C  "
                                      "RMSE={rmse:.2f} \u00b0C"),
                        ), "Fig. S10")

        # ── Figs. 6/7 and S4/S5: basin correlation maps ──────────────
        # The ensemble figure returns the per-model correlation packs,
        # so the per-model figure costs only the plotting. remove=() is
        # the unfiltered variant; v13 also produces AMO/NINO34/PDO
        # variants, none of which the manuscript uses.
        def basin_corr(driver, label, obs_drv, model_drv, models_key):
            packs = s.make_figS_basin_corr_obs_ens(
                obs_chl_ts=obs_full,
                obs_drv_ts=obs_drv,
                model_chl_ts=model_chl_ts,
                model_drv_ts=model_drv,
                common_grid=common_grid,
                driver=driver,
                driver_label=label,
                remove=(),
                obs_sst_for_idx=obs_sst_ts,
                model_sst_for_idx=model_sst_ts,
            ) or {}

            if models_key not in want:
                return
            obs_pack = None
            if obs_drv is not None:
                try:
                    cz = s._filtered_z_modes(
                        obs_full, common_grid, s.LAG_PERIOD, "chl::OBS",
                        s.SPATIAL_FILTER_DEG, interp_gaps=True,
                        remove=(), indices={})
                    dz = s._filtered_z_modes(
                        obs_drv, common_grid, s.LAG_PERIOD,
                        f"{driver.lower()}::OBS", s.SPATIAL_FILTER_DEG,
                        remove=(), indices={})
                    r, pv = s._corr_map_lag0(dz, cz)
                    obs_pack = (r, s._fdr_mask(pv))
                except Exception as exc:
                    logger.warning(f"  obs pack for {driver} failed: {exc}")
            s.make_figS_basin_corr_per_model(
                model_packs=packs, common_grid=common_grid,
                driver=driver, obs_pack=obs_pack, remove=())

        if common_grid is not None and model_chl_ts:
            sst_label = getattr(s, "SST_OBS_NAME", "NOAA-ERSSTv5") + " SST"
            for key, (driver, label, models_key) in (
                    ("fig06_corr_chl_sst",
                     ("SST", sst_label, "figS04_corr_chl_sst_models")),
                    ("fig07_corr_chl_mld",
                     ("MLD", "ORAS5 MLD", "figS05_corr_chl_mld_models"))):
                if key not in want and models_key not in want:
                    continue
                obs_drv = obs_sst_ts if driver == "SST" else obs_mld_ts
                mod_drv = model_sst_ts if driver == "SST" else model_mld_ts
                run(key if key in want else models_key,
                    lambda d=driver, l=label, o=obs_drv, m=mod_drv,
                           mk=models_key: basin_corr(d, l, o, m, mk),
                    f"Figs. {'6/S4' if driver == 'SST' else '7/S5'}")

        # ── Fig. 8: pointwise sea-ice / Chl-a lag correlation ────────
        if common_grid is not None and model_chl_ts:
            run("fig08_seaice_lagcorr",
                lambda: s.make_figS_seaice_chl_spatial_corr(
                    obs_chl_ts=obs_full,
                    obs_siconc_ts=self._obs_siconc_ts(),
                    model_chl_ts=model_chl_ts,
                    model_siconc_ts=model_siconc_ts,
                    common_grid=common_grid),
                "Fig. 8")

        # ── Fig. 9: polar light coupling ─────────────────────────────
        if common_grid is not None and model_chl_ts and self._model_rsds_ts:
            run("fig09_light_polar_coupling",
                lambda: s.make_fig_light_polar_coupling(
                    obs_chl_ts=obs_full,
                    obs_rsds_ts=self._obs_rsds_ts,
                    obs_siconc_ts=self._obs_siconc_ts(),
                    model_chl_ts=model_chl_ts,
                    model_rsds_ts=self._model_rsds_ts,
                    model_siconc_ts=model_siconc_ts,
                    common_grid=common_grid),
                "Fig. 9")
        elif "fig09_light_polar_coupling" in want:
            logger.warning("  Fig. 9 skipped: no model rsds accumulated")

        # ── Fig. 11: Chl:C decomposition ─────────────────────────────
        if _CHLC is not None:
            run("fig11_chlc_decomposition",
                lambda: _CHLC.main(["--out", str(out_dir)]),
                "Fig. 11")
        elif "fig11_chlc_decomposition" in want:
            logger.warning("  Fig. 11 skipped: chlc_decomposition not "
                           "importable")

        # ── Fig. S9: interannual anomaly Hovmoller ───────────────────
        if model_seasonal:
            run("figS09_chl_anomaly_hovmoller",
                lambda: s.make_fig3_hovmoller(
                    obs_full, model_seasonal, obs_clim, model_chl_ts),
                "Fig. S9")

        # The cloud-cover bias map and the whole lag-correlation and
        # sea-ice-memory block used to run here unconditionally. None of
        # those figures appears in the manuscript or its Supporting
        # Information, and the lag block re-loaded and regridded every
        # model's full monthly record, which is where the hours went.
        # They are reachable from the standalone script if wanted.

        logger.success(f"Figures written to {out_dir}")
