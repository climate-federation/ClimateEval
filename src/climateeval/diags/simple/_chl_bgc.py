"""
BGC Chl-a evaluation diagnostic for ClimateEval.

Produces:
  - Standard climateeval metrics table (RMSE, Pearson r, EMD) for HTML report
  - All 12 paper figures in paper_figures/

Figures are generated by calling functions from example_chl_nodatabse5.py,
which is imported once at module load time.
"""
from __future__ import annotations

import sys
import warnings
from pathlib import Path
from typing import TYPE_CHECKING, Any

import numpy as np
import xarray as xr
from esmvalcore.preprocessor import climate_statistics, regrid
from loguru import logger

from climateeval import Coordinate
from climateeval._config import setup_esmvaltool_config_and_logging
from climateeval.diags._utils import DEFAULT_GRID
from climateeval.diags.simple._base import SimpleDiagnostic

if TYPE_CHECKING:
    from iris.cube import Cube, CubeList

# ── Import standalone script once at module load ──────────────────────────────
_CLIM_ROOT = Path("/home/b/b384036/ClimateEval")
if str(_CLIM_ROOT) not in sys.path:
    sys.path.insert(0, str(_CLIM_ROOT))

OUT_DIR = _CLIM_ROOT / "paper_figures"
OUT_DIR.mkdir(exist_ok=True)


def _import_script():
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "chl_script",
        _CLIM_ROOT / "example_chl_nodatabse5.py",
    )
    mod = importlib.util.module_from_spec(spec)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        spec.loader.exec_module(mod)
    return mod


_S = _import_script()


class ChlBGCEvaluation(SimpleDiagnostic):
    """
    Full Chl-a BGC evaluation diagnostic.

    Per model:
      1. _get_cube()    — select the 4D surface chl cube from multi-cube input
      2. _preprocess()  — regrid to 2x2, compute time mean → metrics table
      3. get_output()   — run all 12 figure phases, then call super() for metrics

    Multi-model figures (fig1+2, fig3, fig4) accumulate model_clim/model_seasonal
    across all get_output() calls and are written on the last model.
    """

    _final_coordinates = (Coordinate("lat"), Coordinate("lon"))

    # Shared state across models — populated in get_output()
    _obs_full: Any = None
    _obs_clim: Any = None
    _model_clim: dict = {}
    _model_seasonal: dict = {}
    _model_chl_ts: dict = {}
    _common_grid: Any = None
    _obs_mld_ts: Any = None
    _obs_sst_ts: Any = None
    _model_mld_ts: dict = {}
    _model_sst_ts: dict = {}
    _model_siconc_ts: dict = {}
    _models_processed: list = []

    # ------------------------------------------------------------------ #
    # Cube selection and preprocessing                                     #
    # ------------------------------------------------------------------ #

    def _get_cube(self, data, variable):
        """Select the full 4D chl cube from multi-cube CubeList."""
        import iris
        chl_cubes = data.extract(iris.Constraint(
            cube_func=lambda c: (
                c.var_name == "chl" or
                "chlorophyll" in c.name().lower()
            )
        ))
        four_d = [c for c in chl_cubes if c.ndim == 4]
        if four_d:
            cube = four_d[0]
        elif chl_cubes:
            cube = chl_cubes[0]
        else:
            raise ValueError(
                f"No chl cube found. Available: {[c.name() for c in data]}"
            )
        return self._safely_preprocess(cube, variable)

    def _preprocess(self, cube: Cube, variable=None) -> Cube:
        """Select surface level, regrid to 2x2, compute time mean."""
        if cube.ndim == 4:
            cube = cube[..., 0, :, :]
        with setup_esmvaltool_config_and_logging():
            cube = regrid(cube, DEFAULT_GRID, "linear", cache_weights=True)
            cube = climate_statistics(cube, "mean", "full")
        return cube

    # ------------------------------------------------------------------ #
    # get_output — run figures then metrics                                #
    # ------------------------------------------------------------------ #

    def get_output(self, data: Any, data_information: Any) -> Any:
        """Run figure phases for this model, then delegate to parent."""
        model = data_information.name
        logger.info(f"ChlBGCEvaluation: processing {model}")

        try:
            self._accumulate_model_data(model)
        except Exception as exc:
            import traceback
            logger.warning(f"  [{model}] data accumulation failed: {exc}")
            logger.opt(colors=False).warning(traceback.format_exc())

        # Call parent for metrics table
        result = super().get_output(data, data_information)

        # After last model — generate multi-model figures
        self._models_processed.append(model)
        expected = [m for m in _S.MODELS if m in self._model_clim or
                    m == model]
        if len(self._models_processed) >= len(_S.MODELS):
            try:
                self._run_multi_model_figures()
            except Exception as exc:
                import traceback
                logger.warning(f"  Multi-model figures failed: {exc}")
                logger.opt(colors=False).warning(traceback.format_exc())

        return result

    # ------------------------------------------------------------------ #
    # Data accumulation — called once per model                           #
    # ------------------------------------------------------------------ #

    def _accumulate_model_data(self, model: str) -> None:
        """Load all variables for one model and store in class state."""
        s = _S

        # Load obs once
        if self._obs_full is None:
            self._obs_full = s.load_obs_chl()
            self._obs_clim = self._obs_full.mean("time", keep_attrs=True)

        # Chl
        try:
            da = s.load_model_chl(model)
            self._model_chl_ts[model] = da
            clim_native = da.mean("time", keep_attrs=True)
            self._model_clim[model] = s.regrid_to_obs(clim_native,
                                                       self._obs_clim)
            try:
                months = da.groupby("time.month").mean("time")
                regridded = []
                for m in months.month.values:
                    re = s.regrid_to_obs(months.sel(month=m), self._obs_clim)
                    regridded.append(re.expand_dims(month=[m]))
                self._model_seasonal[model] = xr.concat(regridded, dim="month")
            except Exception as e:
                logger.warning(f"  [{model}] seasonal regrid failed: {e}")
        except FileNotFoundError as e:
            logger.warning(f"  [{model}] chl not found: {e}")
            return

        # MLD — build common grid on first successful load
        try:
            if self._common_grid is None:
                obs_mld = s.load_obs_mld()
                self._obs_mld_ts = obs_mld
                self._common_grid = xr.DataArray(
                    np.zeros((obs_mld.sizes["lat"], obs_mld.sizes["lon"])),
                    dims=("lat", "lon"),
                    coords={"lat": obs_mld.lat, "lon": obs_mld.lon},
                )
            mld_native = s.load_model_mld(model)
            if mld_native is not None:
                mld_re = s.regrid_timeseries(mld_native, self._common_grid)
                self._model_mld_ts[model] = mld_re
        except Exception as e:
            logger.warning(f"  [{model}] MLD failed: {e}")

        # SST
        try:
            if self._obs_sst_ts is None:
                self._obs_sst_ts = s.load_obs_sst()
            sst_native = s.load_model_sst(model)
            if sst_native is not None:
                self._model_sst_ts[model] = sst_native
        except Exception as e:
            logger.warning(f"  [{model}] SST failed: {e}")

        # siconc
        try:
            sic = s.load_model_siconc(model)
            if sic is not None:
                self._model_siconc_ts[model] = sic
        except Exception as e:
            logger.warning(f"  [{model}] siconc failed: {e}")

        logger.success(f"  [{model}] data accumulated")

    # ------------------------------------------------------------------ #
    # Multi-model figures — called once after all models processed        #
    # ------------------------------------------------------------------ #

    def _run_multi_model_figures(self) -> None:
        """Generate all 12 figures using accumulated model data."""
        s = _S
        obs_full = self._obs_full
        obs_clim = self._obs_clim
        model_clim = self._model_clim
        model_seasonal = self._model_seasonal
        model_chl_ts = self._model_chl_ts
        common_grid = self._common_grid
        obs_mld_ts = self._obs_mld_ts
        obs_sst_ts = self._obs_sst_ts
        model_mld_ts = self._model_mld_ts
        model_sst_ts = self._model_sst_ts
        model_siconc_ts = self._model_siconc_ts

        logger.info("=== Generating all figures ===")

        # ── Phase A ───────────────────────────────────────────────────
        if model_clim:
            try:
                s.make_fig1_and_fig2_combined(obs_clim, model_clim)
            except Exception as e:
                logger.warning(f"  Fig 1+2 failed: {e}")
        if model_seasonal:
            try:
                s.make_fig3_hovmoller(obs_full, model_seasonal, obs_clim)
            except Exception as e:
                logger.warning(f"  Fig 3 failed: {e}")
            try:
                s.make_fig4(obs_full, model_seasonal)
            except Exception as e:
                logger.warning(f"  Fig 4 failed: {e}")

        # ── Phase B ───────────────────────────────────────────────────
        if common_grid is not None:
            obs_mld_clim = obs_mld_ts.mean("time", keep_attrs=True) \
                if obs_mld_ts is not None else None

            mld_bias = {}
            model_mld_clim = {}
            for model, mld_re in model_mld_ts.items():
                if obs_mld_clim is not None:
                    clim = mld_re.mean("time")
                    model_mld_clim[model] = clim
                    mld_bias[model] = clim - obs_mld_clim
            if mld_bias:
                try:
                    s.make_bias_map_2x2(
                        mld_bias, obs_mld_clim,
                        vmin=-50, vmax=50, unit_label="m", cmap="RdBu_r",
                        fig_num=5, title="MLD bias: model − ORAS5",
                        filename="fig5_mld_bias.png",
                        stat_fmt="mean={mean:.1f} m  RMSE={rmse:.1f} m",
                    )
                except Exception as e:
                    logger.warning(f"  Fig 5 failed: {e}")

            if obs_sst_ts is not None:
                obs_sst_clim = obs_sst_ts.mean("time", keep_attrs=True)
                sst_bias = {}
                for model, sst_native in model_sst_ts.items():
                    try:
                        sst_clim = sst_native.mean("time", keep_attrs=True)
                        sst_re = s.regrid_to_obs(sst_clim, obs_sst_clim)
                        sst_bias[model] = sst_re - obs_sst_clim
                    except Exception as e:
                        logger.warning(f"  [{model}] SST bias failed: {e}")
                if sst_bias:
                    try:
                        s.make_bias_map_2x2(
                            sst_bias, obs_sst_clim,
                            vmin=-3, vmax=3, unit_label="°C", cmap="RdBu_r",
                            fig_num=6, title="SST bias: model − NOAA-ERSSTv3b",
                            filename="fig6_sst_bias.png",
                            stat_fmt="mean={mean:.2f} °C  RMSE={rmse:.2f} °C",
                        )
                    except Exception as e:
                        logger.warning(f"  Fig 6 failed: {e}")

            try:
                obs_clt = s.load_obs_clt()
                obs_clt_clim = obs_clt.mean("time", keep_attrs=True)
                clt_bias = {}
                for model in s.MODELS:
                    clt_native = s.load_model_clt(model)
                    if clt_native is not None:
                        try:
                            clt_clim = clt_native.mean("time", keep_attrs=True)
                            clt_re = s.regrid_to_obs(clt_clim, obs_clt_clim)
                            clt_bias[model] = clt_re - obs_clt_clim
                        except Exception as e:
                            logger.warning(f"  [{model}] clt bias failed: {e}")
                if clt_bias:
                    s.make_bias_map_2x2(
                        clt_bias, obs_clt_clim,
                        vmin=-20, vmax=20, unit_label="%", cmap="RdBu_r",
                        fig_num=7, title="Cloud cover bias: model − ESA-CCI AVHRR",
                        filename="fig7_clt_bias.png",
                        stat_fmt="mean={mean:.2f} %  RMSE={rmse:.2f} %",
                    )
            except Exception as e:
                logger.warning(f"  Fig 7 failed: {e}")

        # ── Phase C ───────────────────────────────────────────────────
        if common_grid is not None and obs_mld_ts is not None:
            hov_maps = {}
            for model in model_chl_ts:
                try:
                    mld_native = s.load_model_mld(model)
                    if mld_native is None:
                        continue
                    mld_re = s.regrid_timeseries(mld_native, common_grid)
                    chl_re = s.regrid_timeseries(
                        model_chl_ts[model], common_grid)
                    obs_chl_re = s.regrid_timeseries(obs_full, common_grid)
                    hov = s.compute_hovmoller_mld_chl_correlation(
                        mld_re, chl_re, obs_chl_re)
                    hov_maps[model] = hov
                except Exception as e:
                    logger.warning(f"  [{model}] Hovmoller failed: {e}")
            if hov_maps:
                try:
                    s.make_fig8(hov_maps)
                except Exception as e:
                    logger.warning(f"  Fig 8 failed: {e}")

        # ── Phase D ───────────────────────────────────────────────────
        if common_grid is not None:
            if model_chl_ts and (obs_sst_ts is not None or model_sst_ts):
                try:
                    s.make_fig9_lag_sst(
                        obs_chl_ts=obs_full, obs_sst_ts=obs_sst_ts,
                        model_chl_ts=model_chl_ts,
                        model_sst_ts=model_sst_ts,
                        common_grid=common_grid,
                    )
                except Exception as e:
                    logger.warning(f"  Fig 9 failed: {e}")

            if model_chl_ts and (obs_mld_ts is not None or model_mld_ts):
                try:
                    s.make_fig10_lag_mld(
                        obs_chl_ts=obs_full, obs_mld_ts=obs_mld_ts,
                        model_chl_ts=model_chl_ts,
                        model_mld_ts=model_mld_ts,
                        common_grid=common_grid,
                    )
                except Exception as e:
                    logger.warning(f"  Fig 10 failed: {e}")

        # ── Phase E ───────────────────────────────────────────────────
        if common_grid is not None:
            obs_siconc_ts = s.load_obs_siconc()

            if model_chl_ts and (obs_siconc_ts is not None or
                                  model_siconc_ts):
                try:
                    s.make_fig11_lag_siconc(
                        obs_chl_ts=obs_full,
                        obs_siconc_ts=obs_siconc_ts,
                        model_chl_ts=model_chl_ts,
                        model_siconc_ts=model_siconc_ts,
                        common_grid=common_grid,
                    )
                except Exception as e:
                    logger.warning(f"  Fig 11 failed: {e}")

            if obs_siconc_ts is not None or model_siconc_ts:
                for fn, label in [
                    (s.make_fig12_siconc_memory, "Fig 12"),
                    (s.make_figS1_siconc_memory_seasonal_zone, "Fig S1"),
                ]:
                    try:
                        fn(obs_siconc_ts=obs_siconc_ts,
                           model_siconc_ts=model_siconc_ts,
                           common_grid=common_grid, lag_months=12)
                    except Exception as e:
                        logger.warning(f"  {label} failed: {e}")

        logger.success(f"All figures written to {OUT_DIR}")
